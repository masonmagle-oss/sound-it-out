// Proposed new words (need a recording each, approved by ear). Prints docs/NEW-WORDS-TO-RECORD.md. Usage: node tools/new-words.js > docs/NEW-WORDS-TO-RECORD.md
const fs = require('fs'), path = require('path');
global.window = {}; require('../js/content.js');
const have = new Set(window.WORDPLAY_CONTENT.words.map(w => w.word));
const sounds = new Set(fs.readdirSync(path.join(__dirname, '..', 'sounds')).map(f => f.replace(/\.mp3$/, '')));
const key = u => u.indexOf(':') < 0 ? u : u.slice(u.indexOf(':') + 1);
// [group, level, emoji, word, units]  (units use the app's text:key form; a unit with no existing clip is listed as a new clip)
const P = require('./new-words-data.js');
let group = '', n = 0, wc = 0; const newUnits = new Set();
const lines = ['# New words to record (proposal)', '', 'Generated by `node tools/new-words.js`. Each word needs a recording `sounds/word-<word>.mp3` that Mason approves by ear (see WORKFLOWS, "Make or fix sounds"). Pictures are suggestions. Level is the proposed level; units are shown as text:sound-key. "new clip" means that sound has no recording yet.', ''];
for (const [g, level, emoji, word, units] of P) {
  if (g) { group = g; lines.push('', '## ' + g, '', '| Word | Picture | Level | Units | New clips needed |', '|---|---|---|---|---|'); }
  const dup = have.has(word);
  const need = [];
  if (/'/.test(word) || !sounds.has('word-' + word.toLowerCase())) need.push('word-' + word);   // contractions never reuse a clip (it's is not its)
  units.forEach(u => { const k = key(u); if (k !== '_' && !k.startsWith('word-') && !sounds.has(k) && !/'/.test(k)) { need.push(k + ' (unit)'); newUnits.add(k); } else if (k.startsWith('word-') && !sounds.has(k)) need.push(k); });
  lines.push(`| ${word}${dup ? ' (already in list)' : ''} | ${emoji || '—'} | ${level} | ${units.join(' ')} | ${need.join(', ') || 'none'} |`); n++; if (!dup) wc++;
}
lines.push('', `Total: ${wc} new words, ${newUnits.size} new sound clips (${[...newUnits].join(', ')}), plus a word clip for each word.`);
console.log(lines.join('\n'));
