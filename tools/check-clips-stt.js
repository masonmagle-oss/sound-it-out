// Transcribes word-*, sentence-*, question-* and vocab-* clips with ElevenLabs speech-to-text and lists the ones that do not
// say what their file name says (a word said wrong, a word dropped). Homophones (their/there, its/it's, to/two) show up as
// false alarms. Usage: node --env-file=.env.local tools/check-clips-stt.js [--limit N] [--prefix word-] > docs/CLIP-TRANSCRIPT-CHECK.md
const fs = require('fs'), path = require('path');
const dir = path.resolve(__dirname, '..', 'sounds');
const arg = (n, d) => { const i = process.argv.indexOf('--' + n); return i < 0 ? d : process.argv[i + 1]; };
const prefix = arg('prefix', ''), limit = Number(arg('limit', 99999));
const files = fs.readdirSync(dir).filter(f => /^(word|sentence|question)-/.test(f) && f.startsWith(prefix)).slice(0, limit);
const want = f => f.replace(/\.mp3$/, '').replace(/^(word|sentence|question)-/, '').replace(/-/g, ' ');
const norm = t => t.toLowerCase().replace(/[^a-z ]/g, ' ').replace(/\s+/g, ' ').trim();
(async () => {
  const { ElevenLabsClient } = await import('@elevenlabs/elevenlabs-js');
  const client = new ElevenLabsClient();
  const before = (await client.user.subscription.get()).characterCount;
  const bad = []; let i = 0, done = 0;
  await Promise.all(Array.from({ length: 4 }, async () => {
    while (i < files.length) {
      const f = files[i++];
      try {
        const r = await client.speechToText.convert({ file: fs.createReadStream(path.join(dir, f)), modelId: 'scribe_v2' });
        if (norm(r.text || '') !== norm(want(f))) bad.push([f, want(f), (r.text || '').trim()]);
      } catch (e) { bad.push([f, want(f), 'ERROR ' + e.message.slice(0, 80)]); }
      done++;
    }
  }));
  const after = (await client.user.subscription.get()).characterCount;
  console.log('# Clip transcript check\n\nGenerated by `tools/check-clips-stt.js`. ' + done + ' clips checked, ' + bad.length + ' did not match their file name. Homophones (there/their, its/it\'s, two/to) are false alarms. Credits used: ' + (after - before) + '.\n');
  console.log('| Clip | Should say | Heard |\n|---|---|---|');
  bad.sort().forEach(([f, w, h]) => console.log('| ' + f + ' | ' + w + ' | ' + h.replace(/\|/g, '/') + ' |'));
})().catch(e => { console.error(e.message); process.exit(1); });
