// Measures every clip in sounds/ with ffmpeg (length, loudness, peak, silence at the ends, gaps inside) and lists outliers per group.
// Usage: node tools/analyze-sounds.js > docs/SOUND-ANALYSIS.md      (a sanity check only: it cannot hear, so it never approves a clip)
const fs = require('fs'), path = require('path'), { execFile } = require('child_process');
const dir = path.resolve(__dirname, '..', 'sounds');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.mp3')).sort();
const group = k => (/^(word|sentence|letter|help|question|vocab)-/.exec(k) || [, 'sound'])[1];
const run = f => new Promise(res => execFile('ffmpeg', ['-nostats', '-i', path.join(dir, f), '-af', 'silencedetect=noise=-40dB:d=0.1,ebur128=peak=true,astats', '-f', 'null', '-'], { maxBuffer: 1 << 24 }, (e, so, se) => {
  const num = (re, t = se) => { const m = re.exec(t); return m ? Number(m[1]) : null; };
  const sum = se.slice(se.lastIndexOf('Summary:'));
  const dur = num(/Duration: (\d+):(\d+):([\d.]+)/) === null ? null : (() => { const m = /Duration: (\d+):(\d+):([\d.]+)/.exec(se); return +m[1] * 3600 + +m[2] * 60 + +m[3]; })();
  const starts = [...se.matchAll(/silence_start: ([\d.-]+)/g)].map(m => +m[1]), ends = [...se.matchAll(/silence_end: ([\d.]+) \| silence_duration: ([\d.]+)/g)].map(m => [+m[1], +m[2]]);
  const lead = starts.length && starts[0] <= 0.02 && ends.length ? ends[0][0] : 0;
  const trail = starts.length && ends.length < starts.length ? dur - starts[starts.length - 1] : 0;
  const inner = ends.filter(([e, d], i) => !(starts[i] <= 0.02) && e < dur - 0.02).map(x => x[1]);
  res({ f, k: f.replace(/\.mp3$/, ''), dur, lufs: num(/I:\s+(-?[\d.]+) LUFS/, sum), tp: num(/Peak:\s+(-?[\d.]+) dBFS/, sum), rms: num(/RMS level dB: (-?[\d.]+)/, se.slice(se.lastIndexOf('Overall'))), flat: num(/Flat factor: (-?[\d.inf]+)/, se.slice(se.lastIndexOf('Overall'))), lead, trail, gap: inner.length ? Math.max(...inner) : 0, ok: !e });
}));
(async () => {
  const out = []; let i = 0;
  await Promise.all(Array.from({ length: 6 }, async () => { while (i < files.length) out.push(await run(files[i++])); }));
  const by = {}; out.forEach(r => (by[group(r.k)] = by[group(r.k)] || []).push(r));
  const med = a => { const s = a.filter(x => x != null).sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
  const L = ['# Sound analysis', '', 'Generated by `node tools/analyze-sounds.js`. It measures only: it cannot hear voice quality, pronunciation, or a moaning sound. ' + out.length + ' clips.', ''];
  const flagsAll = [];
  for (const [g, rs] of Object.entries(by)) {
    const md = med(rs.map(r => r.dur)), ml = med(rs.map(r => r.rms));   // RMS, not LUFS: LUFS reads -70 (undefined) for clips under 0.4 s
    const maxDur = { sound: 1.0, word: 1.6, letter: 1.6, help: 12, sentence: 5.5, question: 3, vocab: 3 }[g];
    const flags = [];
    rs.forEach(r => {
      const w = [];
      if (!r.ok || r.dur == null) w.push('could not be read');
      if (r.dur > maxDur) w.push('long (' + r.dur.toFixed(2) + 's)');
      if (r.dur < 0.15) w.push('very short (' + r.dur.toFixed(2) + 's)');
      if (r.rms != null && Math.abs(r.rms - ml) > 4) w.push((r.rms < ml ? 'quiet ' : 'loud ') + r.rms.toFixed(1) + ' dB RMS vs group ' + ml.toFixed(1));
      if (r.tp != null && r.tp > -1) w.push('peak ' + r.tp.toFixed(1) + ' dB (clipping risk)');
      if (r.lead > 0.3) w.push('leading silence ' + r.lead.toFixed(2) + 's');
      if (r.trail > 0.5) w.push('trailing silence ' + r.trail.toFixed(2) + 's');
      if (g !== 'help' && g !== 'sentence' && r.gap > 0.35) w.push('gap inside ' + r.gap.toFixed(2) + 's (said twice or a hesitation?)');
      if (w.length) flags.push('- `' + r.f + '`: ' + w.join('; '));
    });
    L.push('## ' + g + ' (' + rs.length + ' clips, median ' + md.toFixed(2) + 's, median ' + (ml == null ? '?' : ml.toFixed(1)) + ' dB RMS, ' + flags.length + ' flagged)', '', flags.length ? flags.join('\n') : 'Nothing flagged.', '');
    flagsAll.push([g, flags.length]);
  }
  L.push('## Summary', '', flagsAll.map(([g, n]) => g + ': ' + n).join(', '));
  console.log(L.join('\n'));
})();
